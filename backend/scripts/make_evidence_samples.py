def make(doc, path: Path):
    name, stadium, issuer, kind, title, rev, date, intro, rows = doc
    pdf = Pdf().page()
    pdf.text(50, 790, issuer, 9)
    pdf.text(50, 768, title, 16, bold=True)
    pdf.text(50, 748, f"{stadium} - FIFA World Cup 2034", 11)
    y = 726
    for k, v in [("Document type", kind), ("Revision", rev), ("Date", date)]:
        pdf.text(50, y, f"{k}:", 10, bold=True)
        pdf.text(160, y, v, 10)
        y -= 15
    y = paragraph(pdf, y - 10, intro)
    y -= 6
    pdf.band(48, y - 5, 499, 18)
    for x, h in zip([50, 130, 400], ["Reference", "Item", "Stated value"]):
        pdf.text(x, y, h, 9, bold=True)
    y -= 20
    for ref, item, value in rows:
        for x, c in zip([50, 130, 400], [ref, item, value]):
            pdf.text(x, y, c, 9)
        pdf.rule(50, y - 6, 545, y - 6, 0.3)
        y -= 19
    footer(pdf, 1, 1)
    pdf.save(path)


def main():
    out = {
        "note": "Generated by backend/scripts/make_evidence_samples.py. Do not edit.",
        "files": [],
    }
    for doc in DOCS:
        path = ROOT / "samples" / doc[0]
        make(doc, path)
        reader = PdfReader(path)
        pages = [
            {"page": i + 1, "text": p.extract_text() or ""} for i, p in enumerate(reader.pages)
        ]
        out["files"].append({"name": doc[0], "size": path.stat().st_size, "pages": pages})
    (ROOT / "readings.json").write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n")
    print(f"{len(DOCS)} evidence documents written; footer: {FOOTER[:20]}…")


if __name__ == "__main__":
    main()
