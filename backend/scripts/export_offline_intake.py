"""Export what the intake pipeline reads from each sample document, for the
frontend's offline demo (used when the backend is not running).

Runs the real backend pipeline (upload, classify, file, check) in a temporary
folder with the sample reader in place of the model, then saves each file's
filing proposal and extracted figures. No Azure calls.

Run from backend/:  poetry run python -m scripts.export_offline_intake
Output: data/progress/offline-readings.json
"""

import asyncio
import json
import tempfile
from pathlib import Path

from fastapi.testclient import TestClient
from pydantic import SecretStr

from app.config import Settings
from app.documents import DocumentStore
from app.intake import IntakeStore, extract
from app.main import create_app
from scripts.sample_reader import SampleReader

DATA = Path(__file__).resolve().parents[2] / "data"
SAMPLES = DATA / "progress"
ORIGIN = {"Origin": "http://localhost:3000"}
FIELDS = ("kind", "stadium_id", "element", "as_of", "revision", "title", "evidence_page", "evidence_quote", "confidence")


def main():
    files = sorted(SAMPLES.glob("*/*/*.pdf")) + sorted(SAMPLES.glob("revised/*.pdf"))
    out = {"note": "Generated by backend/scripts/export_offline_intake.py. Do not edit.", "files": []}
    with tempfile.TemporaryDirectory() as tmp:
        settings = Settings(
            _env_file=None, azure_openai_endpoint="https://example.openai.azure.com",
            azure_openai_api_key=SecretStr("offline"), data_dir=Path(tmp), repo_data_dir=DATA,
        )
        store = DocumentStore(Path(tmp))
        with TestClient(create_app(settings, SampleReader(settings), store)) as client:
            for path in files:
                with path.open("rb") as f:
                    doc = client.post(
                        "/intake/documents", files={"file": (path.name, f, "application/pdf")}, headers=ORIGIN
                    ).json()
                filing = {k: doc[k] for k in ("kind", "stadium_id", "element", "as_of", "revision")}
                client.post(f"/intake/documents/{doc['document_id']}/file", json=filing, headers=ORIGIN)
                out["files"].append({
                    "name": path.name,
                    "size": path.stat().st_size,
                    "folder": path.relative_to(SAMPLES).parts[0],
                    "pages": doc["pages"],
                    "proposal": {k: doc[k] for k in FIELDS},
                    "id": doc["document_id"],
                })
            # Checking every stadium caches each current document's extraction.
            for stadium in ("aramco", "prince-faisal-bin-fahad", "king-fahad-sports-city"):
                client.post(f"/intake/checks/{stadium}", headers=ORIGIN)
            # rev C of the floodlighting plan is superseded by rev D above; read it on its own too.
            intake = IntakeStore(store)
            for f in out["files"]:
                cached = intake.extraction(f["id"])
                if not cached:
                    data, problems, retried = asyncio.run(
                        extract(SampleReader(settings), f["proposal"]["kind"], store.page_texts(f["id"]))
                    )
                    cached = {"data": data, "problems": problems, "retried": retried}
                f["extraction"] = cached
                del f["id"]
    (SAMPLES / "offline-readings.json").write_text(json.dumps(out, indent=1) + "\n")
    print(f"{len(out['files'])} files exported")


if __name__ == "__main__":
    main()
